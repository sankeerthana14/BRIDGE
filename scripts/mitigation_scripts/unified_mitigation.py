def parse_cav_epsilons(text: str) -> list[float]:
    vals = []
    for item in str(text).split(","):
        item = item.strip()
        if not item:
            continue
        vals.append(float(item))
    if not vals:
        raise ValueError("--cav-epsilons produced an empty sweep")
    if any(not np.isfinite(x) for x in vals):
        raise ValueError("CAV epsilons must be finite")
    return vals


