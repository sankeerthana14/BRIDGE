def main():
    args = parse_args()

    random.seed(args.seed)
    np.random.seed(args.seed)
    torch.manual_seed(args.seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(args.seed)

    args.output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    if args.rank != 4:
        raise ValueError(
            "Final frozen M2 controller uses rank=4."
        )
    if float(args.alpha) != 1.0:
        raise ValueError(
            "Final frozen M2 controller uses alpha=1."
        )
    if int(args.behavior_steering_layer_1based) != 20:
        raise ValueError(
            "Final frozen M2 controller uses paper steering layer 20."
        )

    required_paths = [
        args.manifest,
        args.probe_root,
        args.m2_artifact_dir,
        args.healthbench_jsonl,
        args.simple_evals_repo,
    ]

    for path in required_paths:
        if not path.exists():
            raise FileNotFoundError(path)

    if args.stage in {"generate", "all"}:
        if not args.model_path.exists():
            raise FileNotFoundError(args.model_path)

    manifest = load_manifest(
        args.manifest
    )

    generation_path = (
        args.output_dir
        / "mitigation_generations.jsonl"
    )

    if args.stage in {"generate", "all"}:
        generation_path = generate_unified_mitigation_suite(
            args,
            manifest,
        )

    if args.stage in {"evaluate", "all"}:
        release_cuda()
        run_unified_llm_judge_evaluation(
            args,
            generation_path,
        )

    run_metadata = {
        "experiment": "UNIFIED_MITIGATION_WITHOUT_M2_ONLY",
        "model_key": args.model_key,
        "stage": args.stage,
        "cav_epsilons": parse_cav_epsilons(
            args.cav_epsilons
        ),
        "m2_only_rerun": False,
        "m2_artifact_dir": str(
            args.m2_artifact_dir.resolve()
        ),
        "rank": int(args.rank),
        "alpha": float(args.alpha),
        "behavior_steering_layer_1based": int(
            args.behavior_steering_layer_1based
        ),
        "judge_model": args.judge_model,
        "evaluation_policy": (
            "HealthBench exact rubric evaluation with local LLM judge; "
            "no regex behavior evaluator"
        ),
        "ask_abstain_direct_used": False,
        "regex_behavior_classifier_used": False,
    }

    (
        args.output_dir
        / "run_metadata.json"
    ).write_text(
        json.dumps(
            run_metadata,
            indent=2,
        ),
        encoding="utf-8",
    )

    print()
    print("=" * 80)
    print("BRIDGE UNIFIED MITIGATION SUITE COMPLETE")
    print("=" * 80)
