def frozen_probe_layer(probe_dir: Path, model_key: str) -> int:
    """
    Load the selected frozen probe layer if metadata records it; otherwise use
    the already-validated per-model layer from the final probe experiment.
    """
    expected = int(FROZEN_PROBE_LAYER_0BASED[model_key])
    meta_path = probe_dir / "selected_probe_metadata.json"

    if meta_path.exists():
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        candidates = [
            meta.get("selected_layer_0based"),
            meta.get("layer_0based"),
            meta.get("selected_layer"),
        ]
        for value in candidates:
            if value is None:
                continue
            value = int(value)
            if value != expected:
                raise RuntimeError(
                    "Frozen selected probe layer disagrees with the validated "
                    f"BRIDGE configuration for {model_key}: metadata={value}, "
                    f"expected={expected}"
                )
            return value

    return expected


def load_unit_cav(probe_dir: Path) -> np.ndarray:
    path = probe_dir / "cav.npy"
    if not path.exists():
        raise FileNotFoundError(path)

    cav = np.load(path).astype(np.float32)
    cav = np.asarray(cav).reshape(-1)

    if not np.isfinite(cav).all():
        raise RuntimeError(f"Non-finite CAV: {path}")

    norm_cav = float(np.linalg.norm(cav))
    if norm_cav <= 0:
        raise RuntimeError(f"Zero-norm CAV: {path}")

    # The final BRIDGE artifacts already store a unit CAV. Normalize only to
    # protect against serialization drift while preserving its direction.
    cav = cav / norm_cav

    print(
        f"Loaded CAV: {path} | dim={cav.size} | "
        f"stored_norm={norm_cav:.8f} | used_norm={np.linalg.norm(cav):.8f}"
    )
    return cav


